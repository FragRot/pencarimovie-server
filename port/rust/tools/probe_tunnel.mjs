#!/usr/bin/env node
/**
 * probe_tunnel.mjs — end-to-end probe of the Cloudflare tunnel control in the
 * Rust port (`POST /api/tunnel/enable|disable`, `GET /api/tunnel/status`).
 *
 * `cloudflared` is almost never installed on a dev machine, so this harness
 * injects a **stub** through `PM_CLOUDFLARED_BIN` and drives the whole real
 * lifecycle through it. The stub is a tiny node script that behaves like the
 * real binary in the two ways the port actually depends on:
 *
 *   1. it prints the Quick Tunnel URL to stdout (and the `api.trycloudflare.com`
 *      banner line that must be IGNORED), and
 *   2. it serves the `--metrics` endpoints `/ready` ({"status":200}) and
 *      `/quicktunnel` ({"hostname": "…trycloudflare.com"}), and
 *   3. for a Named Tunnel (`run --token …`) it logs the ingress `config="…"`
 *      line whose hostname the port reports as `custom_domain`.
 *
 * A `.cmd` wrapper is used because the port spawns the resolved binary directly:
 * `spawn()` passes `tunnel --url …` as argv, so the "binary" has to be something
 * the OS can execute. Rust's `std::process::Command` runs `.cmd`/`.bat` files
 * through `cmd.exe`, which is enough for a stub (and is by far the least
 * invasive way to fake a binary on Windows).
 *
 * The probe starts its OWN server instance on a free port, with
 * `PM_TUNNEL_NO_REGISTER=1` so a stubbed run never publishes a dead
 * `*.trycloudflare.com` name to the relay.
 *
 * Usage:  node port/rust/tools/probe_tunnel.mjs [--port 8095] [--keep]
 *         (run from the repo root; exit code 0 = every assertion passed)
 */

import { spawn, execFileSync } from 'node:child_process';
import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import os from 'node:os';

const args = process.argv.slice(2);
const argVal = (flag, def) => {
  const i = args.indexOf(flag);
  return i >= 0 && args[i + 1] ? args[i + 1] : def;
};
const KEEP = args.includes('--keep');
const RUST_DIR = path.resolve(import.meta.dirname, '..');
const EXE = path.join(RUST_DIR, 'target', 'release', 'pencarimovie-rust.exe');
const STORAGE_TUNNEL = path.join(RUST_DIR, 'storage', 'tunnel');
const BACKUP = path.join(RUST_DIR, 'storage', 'tunnel.probe-backup');
const STUB_DIR = path.join(RUST_DIR, 'target', 'tunnel-stub');

let failures = 0;
let checks = 0;
function check(label, ok, detail) {
  checks++;
  if (ok) {
    console.log(`PASS  ${label}${detail ? `  (${detail})` : ''}`);
  } else {
    failures++;
    console.log(`FAIL  ${label}${detail ? `  (${detail})` : ''}`);
  }
  return ok;
}

function freePort() {
  return new Promise((resolve, reject) => {
    const srv = net.createServer();
    srv.unref();
    srv.on('error', reject);
    srv.listen(0, '127.0.0.1', () => {
      const port = srv.address().port;
      srv.close(() => resolve(port));
    });
  });
}

async function waitFor(fn, timeoutMs, stepMs = 250) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (await fn()) return true;
    await new Promise((r) => setTimeout(r, stepMs));
  }
  return false;
}

async function req(port, method, p, body) {
  const res = await fetch(`http://127.0.0.1:${port}${p}`, {
    method,
    headers: body ? { 'Content-Type': 'application/json' } : undefined,
    body: body ? JSON.stringify(body) : undefined,
  });
  let json = null;
  try {
    json = await res.json();
  } catch (_) {
    json = null;
  }
  return { status: res.status, json };
}

function alive(pid) {
  if (!pid || pid <= 1) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (e) {
    return e.code === 'EPERM';
  }
}

function taskkill(pid) {
  if (!pid || pid <= 1) return;
  try {
    execFileSync('taskkill', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore' });
  } catch (_) {
    /* already gone */
  }
}

/** The stub `cloudflared`. */
function writeStub() {
  fs.mkdirSync(STUB_DIR, { recursive: true });
  const js = path.join(STUB_DIR, 'cloudflared-stub.mjs');
  const cmd = path.join(STUB_DIR, 'cloudflared-stub.cmd');
  fs.writeFileSync(
    js,
    `// generated by port/rust/tools/probe_tunnel.mjs — a fake cloudflared
import http from 'node:http';

const argv = process.argv.slice(2);
const val = (flag) => {
  const i = argv.indexOf(flag);
  return i >= 0 ? argv[i + 1] : '';
};
const metrics = val('--metrics');            // 127.0.0.1:NNNN
const token = val('--token');
const named = argv.includes('run') && token !== '';
const localPort = process.env.PM_STUB_LOCAL_PORT || '8088';
const host = 'pm-stub-' + Math.random().toString(36).slice(2, 10);
const quickUrl = 'https://' + host + '.trycloudflare.com';
const publicHost = host + '.example.com';

// The banner the parser has to ignore, then the real URL (quick tunnel only).
console.log('INF Requesting new quick Tunnel on trycloudflare.com...');
console.log('INF +--------------------------------------------------------------------------------------------+');
console.log('INF |  https://api.trycloudflare.com                                                            |');
console.log('INF +--------------------------------------------------------------------------------------------+');
if (!named) {
  console.log('INF |  ' + quickUrl + '  |');
  console.log(JSON.stringify({ level: 'info', msg: 'Registered tunnel connection', url: quickUrl }));
} else {
  // Named tunnel: cloudflared logs the ingress config it was handed.
  const cfg = { ingress: [
    { hostname: 'ignore-me.example.com', service: 'http_status:404' },
    { hostname: publicHost, service: 'http://127.0.0.1:' + localPort },
  ] };
  console.log('INF Updated to new configuration config=' + JSON.stringify(JSON.stringify(cfg)) + ' version=5');
}

const port = Number((metrics.split(':')[1] || '0'));
if (port > 0) {
  const server = http.createServer((req, res) => {
    const body = req.url === '/ready'
      ? { status: 200, readyConnections: 1 }
      : named
        ? {}
        : { hostname: quickUrl };
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify(body));
  });
  server.listen(port, '127.0.0.1', () => {
    console.log('INF metrics server on 127.0.0.1:' + port);
  });
}
setInterval(() => {}, 1 << 30);
`,
  );
  fs.writeFileSync(cmd, `@echo off\r\nnode "${js}" %*\r\n`);
  return cmd;
}

function snapshotTunnelDir() {
  if (fs.existsSync(BACKUP)) fs.rmSync(BACKUP, { recursive: true, force: true });
  if (fs.existsSync(STORAGE_TUNNEL)) fs.renameSync(STORAGE_TUNNEL, BACKUP);
}

function restoreTunnelDir() {
  try {
    if (fs.existsSync(STORAGE_TUNNEL)) fs.rmSync(STORAGE_TUNNEL, { recursive: true, force: true });
    if (fs.existsSync(BACKUP)) fs.renameSync(BACKUP, STORAGE_TUNNEL);
  } catch (e) {
    console.log(`WARN  could not restore storage/tunnel: ${e.message}`);
  }
}

const readState = () => {
  try {
    return JSON.parse(fs.readFileSync(path.join(STORAGE_TUNNEL, 'state.json'), 'utf8'));
  } catch (_) {
    return {};
  }
};
const readFileSafe = (p) => (fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '');

async function main() {
  if (!fs.existsSync(EXE)) {
    console.error(`missing ${EXE} — run: cargo build --release`);
    process.exit(2);
  }
  const stub = writeStub();
  const port = Number(argVal('--port', '0')) || (await freePort());

  snapshotTunnelDir();
  const server = spawn(EXE, ['--port', String(port)], {
    cwd: RUST_DIR,
    env: {
      ...process.env,
      PM_CLOUDFLARED_BIN: stub,
      PM_TUNNEL_NO_REGISTER: '1',
      PM_STUB_LOCAL_PORT: String(port),
    },
    stdio: ['ignore', 'pipe', 'pipe'],
    detached: false,
  });
  let serverLog = '';
  server.stdout.on('data', (d) => (serverLog += d.toString()));
  server.stderr.on('data', (d) => (serverLog += d.toString()));

  const cleanup = () => {
    try {
      taskkill(server.pid);
    } catch (_) {}
    const state = readState();
    taskkill(state.pid);
    restoreTunnelDir();
  };

  try {
    const up = await waitFor(async () => {
      try {
        const r = await req(port, 'GET', '/api/version');
        return r.status === 200;
      } catch (_) {
        return false;
      }
    }, 20000, 300);
    if (!check('server answers /api/version', up, `port ${port}`)) return;

    // ── 1. status with no tunnel ───────────────────────────────────────────
    let r = await req(port, 'GET', '/api/tunnel/status');
    check('status: off before enable', r.status === 200 && r.json.enabled === false && r.json.running === false, `enabled=${r.json?.enabled}`);
    check('status: message is the "off" text', (r.json?.message || '') === 'Cloudflare tunnel is off.', r.json?.message);

    // ── 2. quick tunnel ───────────────────────────────────────────────────
    r = await req(port, 'POST', '/api/tunnel/enable', { tunnel_token: '' });
    const quick = r.json || {};
    check('enable(quick): HTTP 200 + ok:1', r.status === 200 && quick.ok === 1, `status ${r.status}`);
    check('enable(quick): tunnel_url is *.trycloudflare.com', /^https:\/\/[a-z0-9-]+\.trycloudflare\.com$/.test(quick.tunnel_url || ''), quick.tunnel_url);
    const deviceId = (quick.public_url || '').match(/^https:\/\/([a-z0-9]+)-tunnel\.pencarimovie\.com$/);
    check('enable(quick): public_url is the device relay', !!deviceId, quick.public_url);
    check('enable(quick): manifest_url follows public_url', (quick.manifest_url || '') === `${quick.public_url}/manifest.json`, quick.manifest_url);
    check('enable(quick): message names the relay', (quick.message || '').startsWith('Tunnel is live at '), quick.message);
    check('enable(quick): pid recorded', quick.pid > 1, `pid ${quick.pid}`);

    const state = readState();
    check('state.json: enabled + pid + metrics_port', state.enabled === true && state.pid === quick.pid && state.metrics_port > 0, JSON.stringify({ pid: state.pid, metrics: state.metrics_port }));
    check('state.json: tunnel_url stored', state.tunnel_url === quick.tunnel_url, state.tunnel_url);
    check('state.json: bin points at the stub', (state.bin || '').toLowerCase().endsWith('cloudflared-stub.cmd'), state.bin);
    check('config.yml: ingress points at the local port', readFileSafe(path.join(STORAGE_TUNNEL, 'config.yml')).includes(`http://127.0.0.1:${port}`));
    const stubLog = readFileSafe(path.join(STORAGE_TUNNEL, 'cloudflared.log'));
    check('cloudflared.log holds the stub URL line', stubLog.includes(quick.tunnel_url), `${stubLog.split('\n').length} lines`);
    check('pid file written', readFileSafe(path.join(STORAGE_TUNNEL, 'cloudflared.pid')).trim() === String(quick.pid));

    // ── 3. status reflects the live process ───────────────────────────────
    r = await req(port, 'GET', '/api/tunnel/status');
    const st = r.json || {};
    check('status: enabled + running', st.enabled === true && st.running === true, `enabled=${st.enabled} running=${st.running}`);
    check('status: same pid as the spawn', st.pid === quick.pid, `pid ${st.pid}`);
    check('status: tunnel_url re-read from the live metrics endpoint', st.tunnel_url === quick.tunnel_url, st.tunnel_url);
    check('status: metrics_port reported', st.metrics_port > 0, `metrics ${st.metrics_port}`);
    check('status: process really alive', alive(st.pid), `pid ${st.pid}`);

    // ── 4. disable round-trip ─────────────────────────────────────────────
    r = await req(port, 'POST', '/api/tunnel/disable', {});
    const off = r.json || {};
    check('disable: ok:1 + disabled', r.status === 200 && off.ok === 1 && off.enabled === false, `status ${r.status}`);
    check('disable: message', off.message === 'Cloudflare tunnel stopped.', off.message);
    check('disable: state.json removed', !fs.existsSync(path.join(STORAGE_TUNNEL, 'state.json')));
    check('disable: pid file removed', !fs.existsSync(path.join(STORAGE_TUNNEL, 'cloudflared.pid')));
    const died = await waitFor(() => !alive(quick.pid), 10000, 250);
    check('disable: the cloudflared process is gone', died, `pid ${quick.pid}`);

    r = await req(port, 'GET', '/api/tunnel/status');
    check('status: off again after disable', r.json.enabled === false && r.json.running === false, `enabled=${r.json?.enabled}`);

    // ── 5. named tunnel via a service-install command line ────────────────
    const jwt = 'eyJhIjoiYWIiLCJ0IjoiY2QifQ==';
    r = await req(port, 'POST', '/api/tunnel/enable', { tunnel_token: `cloudflared.exe service install ${jwt}` });
    const named = r.json || {};
    check('enable(named): HTTP 200 + ok:1', r.status === 200 && named.ok === 1, `status ${r.status}`);
    check('enable(named): custom_domain parsed from the ingress log', /^pm-stub-[a-z0-9]+\.example\.com$/.test(named.custom_domain || ''), named.custom_domain);
    check('enable(named): custom_domains is a list with one host', Array.isArray(named.custom_domains) && named.custom_domains.length === 1, JSON.stringify(named.custom_domains));
    check('enable(named): tunnel_url is https://<custom_domain>', named.tunnel_url === `https://${named.custom_domain}`, named.tunnel_url);
    check('enable(named): manifest_url on the custom domain', named.manifest_url === `https://${named.custom_domain}/manifest.json`, named.manifest_url);
    check('enable(named): message names the domain', (named.message || '').startsWith('Connected to https://'), named.message);
    check('enable(named): the http_status:404 host is skipped', !JSON.stringify(named.custom_domains || []).includes('ignore-me'), JSON.stringify(named.custom_domains));
    check('enable(named): token normalised to the raw JWT', named.tunnel_token === jwt, named.tunnel_token);
    check('token.txt persisted', readFileSafe(path.join(STORAGE_TUNNEL, 'token.txt')).trim() === jwt);

    r = await req(port, 'GET', '/api/tunnel/status');
    const nst = r.json || {};
    check('status(named): enabled + running', nst.enabled === true && nst.running === true);
    check('status(named): custom_domain reported', nst.custom_domain === named.custom_domain, nst.custom_domain);
    check('status(named): message "Live on https://…"', (nst.message || '').startsWith('Live on https://'), nst.message);

    r = await req(port, 'POST', '/api/tunnel/disable', {});
    check('disable(named): ok:1', r.json?.ok === 1 && r.json.enabled === false);
    check('disable(named): token.txt is PRESERVED', readFileSafe(path.join(STORAGE_TUNNEL, 'token.txt')).trim() === jwt);
    const died2 = await waitFor(() => !alive(named.pid), 10000, 250);
    check('disable(named): process gone', died2, `pid ${named.pid}`);

    // ── 6. a saved token is reused when the request carries none ──────────
    r = await req(port, 'POST', '/api/tunnel/enable', {});
    const reused = r.json || {};
    check('enable({}): reuses the saved token (named path)', reused.ok === 1 && /^pm-stub-/.test(reused.custom_domain || ''), reused.custom_domain || reused.message);
    await req(port, 'POST', '/api/tunnel/disable', {});
    const died3 = await waitFor(() => !alive(reused.pid), 10000, 250);
    check('cleanup: last process gone', died3, `pid ${reused.pid}`);

    // Cleanup below is what the assertion above depends on: the port must have
    // killed the stub it spawned, not just forgotten it.
  } finally {
    if (!KEEP) cleanup();
    if (KEEP) console.log(`KEPT: server pid ${server.pid}, storage/tunnel left in place`);
  }

  console.log(`\n${checks - failures}/${checks} checks passed`);
  if (failures > 0) {
    console.log('\n--- server log tail ---');
    console.log(serverLog.split('\n').slice(-40).join('\n'));
  }
  process.exit(failures === 0 ? 0 : 1);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
